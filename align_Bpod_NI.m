%%
function calculate_duration(path)

sampling_rate = 2000;

% target onset to decision window
duration_1 = [];

% target onset to reward (for stage 1)
duration_2 = [];

for i = 1:length(path)
    % ディレクトリの移動
    folderPath = path{i};
    cd(folderPath)

    %% Bpod data
    list = dir('block*.mat');
    list = natsortfiles({list.name});

    RawEvents_Trial = [];
    for m = 1:length(list)
        load(list{m});
        RawEvents_Trial = [RawEvents_Trial saveBlock.RawEvents.Trial];
    end
    trial_start_bpod = zeros(1,length(RawEvents_Trial));
    trial_end_bpod = zeros(1,length(RawEvents_Trial));
    decision_window_start_bpod = zeros(1,length(RawEvents_Trial));
    for n = 1:length(RawEvents_Trial)
        trial_start_bpod(n) = RawEvents_Trial{1,n}.States.StartState(1);
        trial_end_bpod(n) = RawEvents_Trial{1,n}.States.EndState(1);
        decision_window_start_bpod(n) = RawEvents_Trial{1,n}.States.Choice(1); % 1 sec in Bpod
    end

    %% compare
    load('Bpod_NI.mat')
    estim_decision_window_start_ni = trial_start +...
                                        (trial_end-trial_start) .*...
                                        (decision_window_start_bpod-trial_start_bpod)./(trial_end_bpod-trial_start_bpod);

    load('Bpod_NI.mat')
    % target onset to decision window
    temp_1 = (estim_decision_window_start_ni-stim_onset)/sampling_rate;
    duration_1 = [duration_1, temp_1(SelfInitiated==1)];

    % target onset to reward (for stage 1)
    if length(path)==44
        temp_2 = (reward-stim_onset)/sampling_rate;
        duration_2 = [duration_2, temp_2(SelfInitiated==1)];
    end
end

disp('target onset to decision window')
av_1 = mean(duration_1)
se_1 = std(duration_1)/sqrt(length(duration_1))
min_1 = min(duration_1)
max_1 = max(duration_1)

if length(path)==44
    disp('target onset to reward')
    av_2 = mean(duration_2)
    se_2 = std(duration_2)/sqrt(length(duration_2))
    min_2 = min(duration_2)
    max_2 = max(duration_2)
end

